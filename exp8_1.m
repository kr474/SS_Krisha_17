clc;
clear;
close all;
fs = 1000;
t = 0:1/fs:1-1/fs;
x = sin(2*pi*50*t);
N = length(x);
X = fft(x);
f = (0:N-1)*fs/N;
mag = abs(X)/N;
phase = angle(X);
x1 = ifft(X);
subplot(2,2,1);
plot(t,x);
title('Original Signal');
xlabel('Time (s)'); ylabel('Amplitude'); grid on;
subplot(2,2,2);
plot(f,mag);
title('Magnitude Spectrum');
xlabel('Frequency (Hz)'); ylabel('Magnitude'); grid on;
subplot(2,2,3);
plot(f,phase);
title('Phase Spectrum');
xlabel('Frequency (Hz)'); ylabel('Phase (rad)'); grid on;
subplot(2,2,4);
plot(t,real(x1));
title('Reconstructed Signal using IFFT');
xlabel('Time (s)'); ylabel('Amplitude'); grid on;